export function findListing(stockId: string): Listing | undefined {
  return inventory.find((l) => l.stockId === stockId);
}

export function formatPrice(price: number | null): string {
  if (price === null) return "Get Price";
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0,
  }).format(price);
}
